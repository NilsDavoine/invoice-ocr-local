"""results/*.json -> results.md. Every number in results.md comes from here."""
import json
import statistics
from pathlib import Path

from .evaluate import FIELDS

ORDER = ["textlayer_cpu", "rapidocr_cpu", "xiaomi_cuda", "xiaomi_cpu_subset", "xiaomi_cpu"]
TITLES = {
    "textlayer": "No OCR: PDF text layer (upper bound of the rules)",
    "rapidocr": "RapidOCR (PP-OCR det + en PP-OCRv3 rec, ONNX)",
    "xiaomi": "PP-DocLayoutV3 + Xiaomi-OCR-0 (the real tool's pair)",
}


def pct(a, b):
    return "n/a" if not b else f"{100 * a / b:.0f} %"


def summarise(data):
    recs = data["records"]
    n = len(recs)
    flagged = lambda r: r["status"] != "OK"  # noqa: E731
    # reading errors are counted on the normal invoices; the 4 anomalies are measured apart
    with_err = [r for r in recs if not r["all_correct"] and not r["anomaly"]]
    silent = [r for r in recs if r["status"] == "OK" and not r["all_correct"]]
    silent_checked = [r for r in silent if set(r["wrong"]) - {"supplier_name"}]
    clean_ok = [r for r in recs if r["all_correct"] and not r["anomaly"]]
    anomalies = [r for r in recs if r["anomaly"]]
    pages = [s for r in recs for s in r["seconds_per_page"]]
    return {
        "n": n,
        "field_acc": {f: sum(r["correct"][f] for r in recs) / n for f in FIELDS},
        "field_acc_scanned": {f: _mean([r["correct"][f] for r in recs if r["scanned"]]) for f in FIELDS},
        "all_correct": sum(r["all_correct"] for r in recs),
        "with_err": len(with_err), "caught": sum(flagged(r) for r in with_err), "silent": silent,
        "silent_checked": silent_checked,
        "exported_ok": sum(r["status"] == "OK" for r in recs),
        "anomalies": len(anomalies), "anomalies_flagged": sum(flagged(r) for r in anomalies),
        "false_alarms": sum(flagged(r) for r in clean_ok), "clean_ok": len(clean_ok),
        "rejected": sum(r["status"] == "REJECTED" for r in recs),
        "sec_median": statistics.median(pages) if pages else None,
        "sec_mean": statistics.mean(pages) if pages else None,
        "sec_max": max(pages) if pages else None,
        "n_scanned": sum(r["scanned"] for r in recs),
    }


def _mean(xs):
    return sum(xs) / len(xs) if xs else None


def _sec(x):
    return "n/a" if x is None else (f"{x * 1000:.0f} ms" if x < 1 else f"{x:.1f} s")


def write(results_dir="results", out="results.md"):
    runs = {}
    for p in sorted(Path(results_dir).glob("*.json")):
        if p.stem not in ("mutation", "stress"):
            runs[p.stem] = json.loads(p.read_text(encoding="utf-8"))
    keys = [k for k in ORDER if k in runs] + [k for k in runs if k not in ORDER]
    S = {k: summarise(runs[k]) for k in keys}
    L = ["# Results", "",
         "_Generated by `python -m invoice_ocr report` from `results/*.json`. Do not edit by hand._", "",
         "Dataset: fictitious invoices from `python -m invoice_ocr generate` (seed 2026), FR / EN / DE, "
         "three layouts, about half degraded as scans (rotation up to 2°, blur, noise, JPEG). "
         "4 invoices are deliberately inconsistent (wrong total, 20 % rate, broken VAT number checksum, "
         "due date before issue date) and must come out as `TO_VERIFY`.", "",
         "## Runs", "",
         "| Run | Engine | Device | Invoices | Model load |", "|---|---|---|---|---|"]
    for k in keys:
        m = runs[k]["meta"]
        dev = m["device"] + (f" ({m['gpu']})" if m.get("gpu") else "")
        L.append(f"| `{k}` | {TITLES.get(m['engine'], m['engine'])} | {dev} | {m['n']}"
                 f"{' (subset)' if m['subset'] else ''} | {_sec(m['load_seconds']) if m['load_seconds'] else '-'} |")
    L += ["", f"Machine: {runs[keys[0]]['meta']['machine']}." if keys else "", "",
          "## Field accuracy", "", "| Field | " + " | ".join(f"`{k}`" for k in keys) + " |",
          "|---|" + "---|" * len(keys)]
    for f in FIELDS:
        L.append(f"| {f} | " + " | ".join(f"{100 * S[k]['field_acc'][f]:.0f} %" for k in keys) + " |")
    L += ["", "## Invoice level and safety", "",
          "| Measure | " + " | ".join(f"`{k}`" for k in keys) + " |", "|---|" + "---|" * len(keys)]
    rows = [
        ("Invoices with every field right", lambda s: f"{s['all_correct']}/{s['n']} ({pct(s['all_correct'], s['n'])})"),
        ("Normal invoices (no anomaly) with at least one wrong field", lambda s: f"{s['with_err']}"),
        ("... of which flagged TO_VERIFY / rejected (caught)", lambda s: f"{s['caught']}/{s['with_err']} ({pct(s['caught'], s['with_err'])})"),
        ("**Exported OK but wrong (silent errors)**", lambda s: f"**{len(s['silent'])}**"),
        ("... of which on a field the checks cover (not the supplier name)", lambda s: f"{len(s['silent_checked'])}"),
        ("Deliberate anomalies flagged", lambda s: f"{s['anomalies_flagged']}/{s['anomalies']}"),
        ("False alarms (all fields right, no anomaly, still flagged)", lambda s: f"{s['false_alarms']}/{s['clean_ok']}"),
        ("Exported as OK", lambda s: f"{s['exported_ok']}/{s['n']}"),
        ("Time per page, median", lambda s: _sec(s["sec_median"])),
        ("Time per page, mean", lambda s: _sec(s["sec_mean"])),
        ("Time per page, max", lambda s: _sec(s["sec_max"])),
    ]
    for label, fn in rows:
        L.append(f"| {label} | " + " | ".join(fn(S[k]) for k in keys) + " |")
    L += ["", "Time per page covers deskew + layout + reading; field extraction, checks and XML add "
          "a few milliseconds. Model loading is listed separately.", ""]
    for k in keys:
        sil = S[k]["silent"]
        if sil:
            L += [f"Silent errors in `{k}`:", ""]
            for r in sil:
                L.append(f"- {r['id']}: " + "; ".join(f"{f} read {v[0]!r}, truth {v[1]!r}" for f, v in r["wrong"].items()))
            L.append("")
    L += ["## Scanned pages only (field accuracy)", "",
          "| Field | " + " | ".join(f"`{k}`" for k in keys) + " |", "|---|" + "---|" * len(keys)]
    for f in FIELDS:
        L.append(f"| {f} | " + " | ".join(
            "n/a" if S[k]["field_acc_scanned"][f] is None else f"{100 * S[k]['field_acc_scanned'][f]:.0f} %"
            for k in keys) + " |")
    st = Path(results_dir) / "stress.json"
    if st.exists():
        T = json.loads(st.read_text(encoding="utf-8"))
        L += ["", "## Simulated misreads (how much the checks catch)", "",
              f"`python -m invoice_ocr stress`: starting from a perfect reading of the 36 normal invoices, "
              f"one digit of one row is replaced ({T['per_invoice']} trials per invoice, seed {T['seed']}, "
              "70 % of the time by a typical OCR confusion such as 3/8 or 1/7). "
              f"{T['trials']} trials, {T['changed_a_field']} changed at least one extracted field; "
              f"**{T['flagged']} of those ({pct(T['flagged'], T['changed_a_field'])}) were flagged TO_VERIFY**.", "",
              "| Field changed by the misread | Trials | Flagged |", "|---|---|---|"]
        for f, v in T["per_field"].items():
            if v["changed"]:
                L.append(f"| {f} | {v['changed']} | {pct(v['flagged'], v['changed'])} |")
        L += ["", "Not flagged, by design of the checks: the invoice number (no checksum to test it "
              "against) and a date that stays plausible.", ""]
    mut = Path(results_dir) / "mutation.json"
    if mut.exists():
        M = json.loads(mut.read_text(encoding="utf-8"))
        L += ["", "## Mutation test of the guard", "",
              "`python -m tools.mutate` breaks the guarded code on purpose, runs the tests, expects them to "
              "fail, then restores the file from a backup copy and checks the tests pass again.", "",
              "| Mutation | File | Tests with mutation | Tests after restore |", "|---|---|---|---|"]
        for m in M["mutations"]:
            L.append(f"| {m['name']} | `{m['file']}` | {m['with_mutation']} | {m['after_restore']} |")
        L += ["", f"Run at {M['run_at']}."]
    Path(out).write_text("\n".join(L) + "\n", encoding="utf-8")
    _readme_block(keys, S, runs)
    return out


def _readme_block(keys, S, runs, readme="README.md"):
    """Replace the block between the results markers of the README with headline numbers."""
    p = Path(readme)
    if not p.exists():
        return
    text = p.read_text(encoding="utf-8")
    start, end = "<!-- results:start -->", "<!-- results:end -->"
    if start not in text or end not in text:
        return
    L = ["", "| Run | Pages | Every field right | Reading errors caught | Silent errors (of which not the name) | "
         "Anomalies flagged | Time / page (median) |", "|---|---|---|---|---|---|---|"]
    for k in keys:
        s, m = S[k], runs[k]["meta"]
        dev = m["device"] + (f", {m['gpu']}" if m.get("gpu") else "")
        L.append(f"| {TITLES.get(m['engine'], m['engine']).split(' (')[0]} — {dev} | {s['n']} | "
                 f"{pct(s['all_correct'], s['n'])} | {s['caught']}/{s['with_err']} | {len(s['silent'])} ({len(s['silent_checked'])}) | "
                 f"{s['anomalies_flagged']}/{s['anomalies']} | {_sec(s['sec_median'])} |")
    L += ["", "_Copied here by `python -m invoice_ocr report`; full tables in [results.md](results.md)._", ""]
    a, b = text.index(start) + len(start), text.index(end)
    p.write_text(text[:a] + "\n".join(L) + text[b:], encoding="utf-8")
